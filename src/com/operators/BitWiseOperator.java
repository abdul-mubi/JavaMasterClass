package com.operators;

public class BitWiseOperator {

	public static void main(String[] args) {
		int a = 10;
		int b = 20;
		System.out.println(a&b); // Bitwise And
		System.out.println(a|b); // Bitwise OR
		System.out.println(a^b); // Bitwise Ex-OR
		System.out.println(~a); // compliment
		System.out.println(a<<1); // left shift operator
		System.out.println(b>>1); // right shift operator

	}

}
