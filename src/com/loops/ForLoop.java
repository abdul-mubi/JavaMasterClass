package com.loops;

public class ForLoop {

	public static void main(String[] args) {
		for (int i = 1; i<=5; i++ )//Print from 1 to 5
			System.out.println(i);
		
		System.out.println("---------------------------");
		
		for (int i=5; i>0; i--)//Print from 5 to 1
			System.out.println(i);
		
//		for (int i=5; i>0;)
//			System.out.println(i);
		
		
	}

}
